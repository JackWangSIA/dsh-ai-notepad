import { build } from 'esbuild'
import { mkdir, readFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
await mkdir(resolve(root, 'lib'), { recursive: true })
const pkg = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'))
const buildTime = new Date().toISOString()

await build({
  absWorkingDir: root,
  entryPoints: ['src/client.jsx'],
  outfile: 'lib/client.js',
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: ['chrome120'],
  jsx: 'automatic',
  jsxImportSource: 'react',
  external: ['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client'],
  define: {
    __AINP_VERSION__: JSON.stringify(pkg.version),
    __AINP_BUILD_TIME__: JSON.stringify(buildTime),
  },
  banner: {
    js: [
      '/* AI Notepad client half. Generated by scripts/build.mjs; edit src/. */',
      "window.__ModuleLoader__.load({id:'dsh-ai-notepad',factory:function(require){var module={exports:{}};var exports=module.exports;",
    ].join('\n'),
  },
  footer: {
    js: 'return module.exports;\n}});',
  },
  legalComments: 'none',
  logLevel: 'info',
})
